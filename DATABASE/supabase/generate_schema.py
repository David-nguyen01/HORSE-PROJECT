"""Generate a PostgreSQL DDL draft from the current local SQL Server schema.

Requires pyodbc and Windows authentication to the local racehorse_local database.
The output is a draft: triggers and SQL Server-specific check expressions must be
reviewed before applying it to Supabase.
"""

from __future__ import annotations

import re
from pathlib import Path

import pyodbc


DATABASE = "racehorse_local"
CONNECTION = (
    "Driver={ODBC Driver 17 for SQL Server};Server=localhost,1433;"
    f"Database={DATABASE};Trusted_Connection=yes;TrustServerCertificate=yes"
)


def quote(value: str) -> str:
    return '"' + value.replace('"', '""') + '"'


def postgres_type(name: str, max_length: int, precision: int, scale: int) -> str:
    return {
        "uniqueidentifier": "uuid",
        "datetimeoffset": "timestamptz",
        "date": "date",
        "time": "time",
        "int": "integer",
        "bigint": "bigint",
        "tinyint": "smallint",
        "bit": "boolean",
        "varbinary": "bytea",
    }.get(name) or (
        f"numeric({precision},{scale})" if name == "decimal" else
        "text" if max_length == -1 else
        f"varchar({max_length // 2 if name == 'nvarchar' else max_length})"
    )


def unwrap(value: str) -> str:
    value = value.strip()
    while value.startswith("(") and value.endswith(")"):
        depth = 0
        complete = True
        for index, char in enumerate(value):
            depth += (char == "(") - (char == ")")
            if depth == 0 and index < len(value) - 1:
                complete = False
                break
        if not complete:
            break
        value = value[1:-1].strip()
    return value


def postgres_expr(value: str) -> str:
    value = unwrap(value)
    value = re.sub(r"\[([^]]+)\]", lambda match: quote(match.group(1)), value)
    value = re.sub(r"\bN'", "'", value)
    value = re.sub(r"\bSYSDATETIMEOFFSET\s*\(\s*\)", "CURRENT_TIMESTAMP", value, flags=re.I)
    value = re.sub(r"\bGETDATE\s*\(\s*\)", "CURRENT_TIMESTAMP", value, flags=re.I)
    value = re.sub(r"\bNEWID\s*\(\s*\)", "gen_random_uuid()", value, flags=re.I)
    value = re.sub(r"\bISNULL\s*\(", "COALESCE(", value, flags=re.I)
    value = re.sub(r"\bISJSON\s*\(([^()]+)\)\s*=\s*\(?1\)?", r"(\1)::jsonb IS NOT NULL", value, flags=re.I)
    value = re.sub(r"\bLEN\s*\(\s*LTRIM\s*\(\s*RTRIM\s*\(([^()]+)\)\s*\)\s*\)", r"length(btrim(\1))", value, flags=re.I)
    return value


def fetch(cursor, sql: str, *params):
    return cursor.execute(sql, *params).fetchall()


def generate() -> str:
    connection = pyodbc.connect(CONNECTION)
    cursor = connection.cursor()
    output = [
        "-- Generated from the current racehorse_local schema; review before deployment.",
        "-- SQL Server triggers are not included in this file.",
        "CREATE SCHEMA IF NOT EXISTS dbo;",
    ]
    tables = [row[0] for row in fetch(cursor, """
        SELECT name FROM sys.tables WHERE schema_id=SCHEMA_ID('dbo') ORDER BY name
    """)]
    for table in tables:
        rows = fetch(cursor, """
            SELECT c.name, ty.name, c.max_length, c.precision, c.scale,
                   c.is_nullable, dc.definition, c.is_identity, c.is_computed
            FROM sys.columns c JOIN sys.types ty ON c.user_type_id=ty.user_type_id
            LEFT JOIN sys.default_constraints dc ON dc.object_id=c.default_object_id
            WHERE c.object_id=OBJECT_ID(?) ORDER BY c.column_id
        """, f"dbo.{table}")
        definitions = []
        for name, typ, length, precision, scale, nullable, default, identity, computed in rows:
            if computed:
                raise ValueError(f"Computed column requires manual migration: {table}.{name}")
            pgtype = postgres_type(typ, length, precision, scale)
            definition = f"    {quote(name)} {pgtype}"
            if identity:
                definition += " GENERATED BY DEFAULT AS IDENTITY"
            if not nullable:
                definition += " NOT NULL"
            if default is not None:
                expression = postgres_expr(default)
                if typ == "bit" and expression in {"0", "1"}:
                    expression = "FALSE" if expression == "0" else "TRUE"
                definition += f" DEFAULT {expression}"
            definitions.append(definition)
        output.append(f"CREATE TABLE dbo.{quote(table)} (\n" + ",\n".join(definitions) + "\n);")

    for table in tables:
        keys = fetch(cursor, """
            SELECT kc.name, kc.type, c.name, ic.key_ordinal
            FROM sys.key_constraints kc
            JOIN sys.index_columns ic ON ic.object_id=kc.parent_object_id AND ic.index_id=kc.unique_index_id
            JOIN sys.columns c ON c.object_id=ic.object_id AND c.column_id=ic.column_id
            WHERE kc.parent_object_id=OBJECT_ID(?) ORDER BY kc.name, ic.key_ordinal
        """, f"dbo.{table}")
        grouped = {}
        for name, typ, col, _ in keys:
            grouped.setdefault((name, typ), []).append(quote(col))
        for (name, typ), cols in grouped.items():
            kind = "PRIMARY KEY" if typ == "PK" else "UNIQUE"
            output.append(f"ALTER TABLE dbo.{quote(table)} ADD CONSTRAINT {quote(name)} {kind} ({', '.join(cols)});")

    foreign_keys = fetch(cursor, """
        SELECT fk.name, OBJECT_NAME(fk.parent_object_id), pc.name,
               OBJECT_NAME(fk.referenced_object_id), rc.name, fk.delete_referential_action_desc,
               fkc.constraint_column_id
        FROM sys.foreign_keys fk
        JOIN sys.foreign_key_columns fkc ON fkc.constraint_object_id=fk.object_id
        JOIN sys.columns pc ON pc.object_id=fkc.parent_object_id AND pc.column_id=fkc.parent_column_id
        JOIN sys.columns rc ON rc.object_id=fkc.referenced_object_id AND rc.column_id=fkc.referenced_column_id
        WHERE OBJECT_SCHEMA_NAME(fk.parent_object_id)='dbo'
        ORDER BY fk.name, fkc.constraint_column_id
    """)
    grouped = {}
    for name, table, parent, target, reference, on_delete, _ in foreign_keys:
        item = grouped.setdefault(name, (table, target, on_delete, [], []))
        item[3].append(quote(parent))
        item[4].append(quote(reference))
    for name, (table, target, on_delete, parents, references) in grouped.items():
        output.append(
            f"ALTER TABLE dbo.{quote(table)} ADD CONSTRAINT {quote(name)} "
            f"FOREIGN KEY ({', '.join(parents)}) REFERENCES dbo.{quote(target)} "
            f"({', '.join(references)}) ON DELETE {on_delete.replace('_', ' ')};"
        )

    checks = fetch(cursor, """
        SELECT OBJECT_NAME(parent_object_id), name, definition FROM sys.check_constraints
        WHERE OBJECT_SCHEMA_NAME(parent_object_id)='dbo' ORDER BY parent_object_id, name
    """)
    for table, name, definition in checks:
        expression = postgres_expr(definition)
        if table == "racetracks" and name == "ck_racetracks_operating_hours":
            expression = expression.replace('"closes_next_day"=(1)', '"closes_next_day"=TRUE')
        output.append(
            f"ALTER TABLE dbo.{quote(table)} ADD CONSTRAINT {quote(name)} "
            f"CHECK ({expression});"
        )

    indexes = fetch(cursor, """
        SELECT OBJECT_NAME(i.object_id), i.name, i.is_unique, i.filter_definition,
               c.name, ic.key_ordinal, ic.is_included_column
        FROM sys.indexes i
        JOIN sys.index_columns ic ON ic.object_id=i.object_id AND ic.index_id=i.index_id
        JOIN sys.columns c ON c.object_id=ic.object_id AND c.column_id=ic.column_id
        WHERE OBJECT_SCHEMA_NAME(i.object_id)='dbo' AND i.is_primary_key=0
          AND i.is_unique_constraint=0 AND i.is_hypothetical=0 AND i.name IS NOT NULL
        ORDER BY i.object_id, i.index_id, ic.key_ordinal, ic.index_column_id
    """)
    grouped = {}
    for table, name, unique, predicate, col, _, included in indexes:
        item = grouped.setdefault((table, name), (unique, predicate, [], []))
        item[3 if included else 2].append(quote(col))
    for (table, name), (unique, predicate, columns, include) in grouped.items():
        line = f"CREATE {'UNIQUE ' if unique else ''}INDEX {quote(name)} ON dbo.{quote(table)} ({', '.join(columns)})"
        if include:
            line += f" INCLUDE ({', '.join(include)})"
        if predicate:
            line += f" WHERE {postgres_expr(predicate)}"
        output.append(line + ";")

    output.append("REVOKE ALL ON SCHEMA dbo FROM PUBLIC;")
    output.append("-- Database role used by the Spring backend needs USAGE and table privileges on dbo.")
    return "\n\n".join(output) + "\n"


if __name__ == "__main__":
    destination = Path(__file__).with_name("01_schema_draft.sql")
    destination.write_text(generate(), encoding="utf-8")
    print(destination)
